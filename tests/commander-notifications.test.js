const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { JSDOM } = require('jsdom');
test('notifications show safe text at the top right and use theme colors', () => {
  const dom = new JSDOM('<!doctype html><body></body>', { runScripts: 'outside-only' });
  const context = dom.getInternalVMContext();
  for (const file of ['node_modules/notyf/notyf.min.js', 'media/commander-notifications.js']) new vm.Script(fs.readFileSync(path.join(__dirname, '..', file), 'utf8')).runInContext(context);
  const notifications = dom.window.CommanderNotifications.create({ closeLabel: 'Close' });
  notifications.show('<img src=x onerror=alert(1)>', 'error');
  const toast = dom.window.document.querySelector('.notyf__toast');
  assert.equal(toast.querySelector('.notyf__message').textContent, '<img src=x onerror=alert(1)>');
  assert.equal(toast.querySelector('img'), null);
  assert.equal(toast.querySelector('button').getAttribute('aria-label'), 'Close');
  assert.equal(dom.window.document.querySelector('.notyf').style.justifyContent, 'flex-start');
  const css = fs.readFileSync(path.join(__dirname, '../media/commander-notifications.css'), 'utf8');
  assert.match(css, /--vscode-notifications-background/);
  assert.match(css, /--vscode-focusBorder/);
  dom.window.close();
});
